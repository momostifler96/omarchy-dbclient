function resolve(setting, localeName) {
  var lang = String(setting || "auto")
  if (lang === "auto") lang = String(localeName || "en").slice(0, 2)
  return strings[lang] ? lang : "en"
}

function tr(lang, key, a, b) {
  var table = strings[lang] || strings.en
  var s = table[key] !== undefined ? table[key] : (strings.en[key] !== undefined ? strings.en[key] : key)
  if (a !== undefined) s = s.replace("%1", a)
  if (b !== undefined) s = s.replace("%2", b)
  return s
}

